"""Time-aware A* for Mode B's compact CSR road graph.

This module is deliberately separate from the existing Static and Dynamic A*
implementations. It chooses a route by modelled travel time, using compact
per-edge highway codes and configured edge-condition statuses. It uses no live
traffic feed and does not load or modify Mode A files.

The caller must provide the edge_highway_codes array that was generated by
build_compact_graph.py. The synthetic self-test does not open project graph files.
"""
from __future__ import annotations

import argparse
import heapq
import math
import time
from typing import Any, Mapping

import numpy as np


DEFAULT_BASE_SPEEDS_KMH: dict[str, float] = {
    "motorway": 65.0,
    "motorway_link": 40.0,
    "trunk": 55.0,
    "trunk_link": 35.0,
    "primary": 40.0,
    "primary_link": 30.0,
    "secondary": 35.0,
    "secondary_link": 27.0,
    "tertiary": 30.0,
    "tertiary_link": 23.0,
    "unclassified": 25.0,
    "residential": 20.0,
    "living_street": 10.0,
    "service": 12.0,
    "road": 20.0,
}

DEFAULT_CONDITION_SPEED_FACTORS: dict[str, float] = {
    "normal": 1.0,
    "congested": 0.55,
    "blocked": 0.0,
}

EARTH_RADIUS_KM = 6371.0088


def haversine_km(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    """Return great-circle distance in kilometres."""
    p1 = math.radians(lat1)
    p2 = math.radians(lat2)
    dp = math.radians(lat2 - lat1)
    dl = math.radians(lon2 - lon1)
    a = math.sin(dp / 2.0) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2.0) ** 2
    a = min(1.0, max(0.0, a))
    return 2.0 * EARTH_RADIUS_KM * math.asin(math.sqrt(a))


def load_highway_codes(data_dir: str, expected_edge_count: int) -> tuple[np.ndarray, dict[int, str]]:
    """Load and validate edge highway codes from the compact graph directory."""
    from pathlib import Path
    import json

    root = Path(data_dir)
    metadata_path = root / "graph_metadata.json"
    if not metadata_path.is_file():
        raise FileNotFoundError(f"Compact graph metadata not found: {metadata_path}")
    metadata = json.loads(metadata_path.read_text(encoding="utf-8"))
    array_name = metadata.get("edge_highway_codes_file", "edge_highway_codes.npy")
    array_path = root / str(array_name)
    if not array_path.is_file():
        raise FileNotFoundError(
            f"Compact highway-code array not found: {array_path}. "
            "Rebuild the compact graph with the updated build_compact_graph.py first."
        )
    highway_codes = np.load(array_path, mmap_mode="r")
    if highway_codes.ndim != 1 or len(highway_codes) != int(expected_edge_count):
        raise ValueError(
            "Highway-code array does not align with CSR edges: "
            f"expected {expected_edge_count:,} entries, got shape {highway_codes.shape}."
        )
    raw_mapping = metadata.get("highway_code_to_name", {})
    if not isinstance(raw_mapping, dict) or not raw_mapping:
        raise ValueError("Compact graph metadata is missing highway_code_to_name.")
    code_to_name: dict[int, str] = {}
    for raw_code, name in raw_mapping.items():
        try:
            code = int(raw_code)
        except (TypeError, ValueError) as exc:
            raise ValueError(f"Invalid highway code in metadata: {raw_code!r}") from exc
        code_to_name[code] = str(name)
    if 0 not in code_to_name:
        code_to_name[0] = "road"
    return highway_codes, code_to_name


def time_astar(
    graph: Any,
    start: int,
    goal: int,
    edge_highway_codes: np.ndarray,
    highway_code_to_name: Mapping[int, str],
    conditions: Mapping[tuple[int, int], Mapping[str, Any]] | None = None,
    base_speeds_kmh: Mapping[str, float] | None = None,
    condition_speed_factors: Mapping[str, float] | None = None,
) -> dict[str, Any] | None:
    """Find a path minimizing modelled travel time.

    ``graph`` must expose CSR arrays ``indptr``, ``targets``, ``distances`` and
    ``vertex_count``, plus ``coordinates(node) -> (latitude, longitude)``.
    ``edge_highway_codes`` must be aligned one-for-one with CSR edge positions.
    Conditions use zero-based directed-edge keys ``(source_index, target_index)``.
    The returned distance is physical road distance; ``estimated_time_minutes``
    is the objective used by this search. Returns None if no traversable route exists.
    """
    started = time.perf_counter()
    vertex_count = int(graph.vertex_count)
    start = int(start)
    goal = int(goal)
    if not (0 <= start < vertex_count and 0 <= goal < vertex_count):
        raise ValueError("Start or goal is outside the compact graph vertex range.")
    if len(edge_highway_codes) != int(graph.edge_count):
        raise ValueError(
            f"Highway-code array length {len(edge_highway_codes)} does not match "
            f"graph edge count {graph.edge_count}."
        )

    speeds = dict(DEFAULT_BASE_SPEEDS_KMH)
    if base_speeds_kmh:
        speeds.update({str(key).strip().lower(): float(value) for key, value in base_speeds_kmh.items()})
    if "road" not in speeds or any(not math.isfinite(value) or value <= 0 for value in speeds.values()):
        raise ValueError("All baseline road speeds must be positive and finite, including 'road'.")

    factors = dict(DEFAULT_CONDITION_SPEED_FACTORS)
    if condition_speed_factors:
        factors.update({str(key).strip().lower(): float(value) for key, value in condition_speed_factors.items()})
    if any(not math.isfinite(value) or value < 0 or value > 1 for value in factors.values()):
        raise ValueError("Condition speed factors must be finite values within [0, 1].")
    if "normal" not in factors or "blocked" not in factors:
        raise ValueError("Condition factors must define 'normal' and 'blocked'.")

    if start == goal:
        return {
            "path": [start],
            "edge_indices": [],
            "distance_km": 0.0,
            "estimated_time_minutes": 0.0,
            "time_cost_minutes": 0.0,
            "expanded_nodes": 0,
            "elapsed_ms": (time.perf_counter() - started) * 1000.0,
            "algorithm": "time_astar",
        }

    edge_conditions = conditions or {}
    # Since the configured speeds never exceed the fastest baseline speed, straight-line
    # distance divided by that maximum speed is an admissible time lower bound (scaled
    # slightly down to tolerate small coordinate/distance rounding differences).
    maximum_speed = max(speeds.values())

    def heuristic_minutes(node: int) -> float:
        node_lat, node_lon = graph.coordinates(node)
        goal_lat, goal_lon = graph.coordinates(goal)
        return 0.99 * haversine_km(node_lat, node_lon, goal_lat, goal_lon) / maximum_speed * 60.0

    open_heap: list[tuple[float, int]] = [(heuristic_minutes(start), start)]
    g_time: dict[int, float] = {start: 0.0}
    g_distance: dict[int, float] = {start: 0.0}
    came_from: dict[int, int] = {}
    came_from_edge: dict[int, int] = {}
    closed: set[int] = set()
    expanded = 0
    epsilon = 1e-9

    while open_heap:
        current_f, current = heapq.heappop(open_heap)
        current_time = g_time.get(current)
        if current_time is None or current in closed:
            continue
        if current_f > current_time + heuristic_minutes(current) + epsilon:
            continue
        if current == goal:
            path = [goal]
            reverse_edge_indices = []
            node = goal
            while node in came_from:
                reverse_edge_indices.append(came_from_edge[node])
                node = came_from[node]
                path.append(node)
            path.reverse()
            reverse_edge_indices.reverse()
            path_edge_indices = reverse_edge_indices
            elapsed_ms = (time.perf_counter() - started) * 1000.0
            return {
                "path": path,
                "edge_indices": path_edge_indices,
                "distance_km": float(g_distance[goal]),
                "estimated_time_minutes": float(current_time),
                "time_cost_minutes": float(current_time),
                "expanded_nodes": expanded,
                "elapsed_ms": elapsed_ms,
                "algorithm": "time_astar",
            }

        closed.add(current)
        expanded += 1
        row_start = int(graph.indptr[current])
        row_end = int(graph.indptr[current + 1])
        for edge_index in range(row_start, row_end):
            neighbor = int(graph.targets[edge_index])
            if neighbor in closed:
                continue
            distance_km = float(graph.distances[edge_index])
            if not math.isfinite(distance_km) or distance_km <= 0.0:
                continue

            condition = edge_conditions.get((current, neighbor), {}) or {}
            status = str(condition.get("status", "normal")).strip().lower()
            if status == "blocked":
                continue
            if status not in factors:
                status = "normal"
            speed_factor = float(factors[status])
            if speed_factor <= 0.0:
                continue

            code = int(edge_highway_codes[edge_index])
            road_class = str(highway_code_to_name.get(code, "road")).strip().lower() or "road"
            baseline_speed = float(speeds.get(road_class, speeds["road"]))
            effective_speed = baseline_speed * speed_factor
            if not math.isfinite(effective_speed) or effective_speed <= 0.0:
                continue

            edge_minutes = distance_km / effective_speed * 60.0
            tentative_time = current_time + edge_minutes
            if tentative_time + epsilon < g_time.get(neighbor, math.inf):
                g_time[neighbor] = tentative_time
                g_distance[neighbor] = g_distance[current] + distance_km
                came_from[neighbor] = current
                came_from_edge[neighbor] = edge_index
                priority = tentative_time + heuristic_minutes(neighbor)
                heapq.heappush(open_heap, (priority, neighbor))

    return None


def _self_test() -> None:
    """Verify road-speed route choice and blocked-edge handling on a tiny graph."""
    class TinyGraph:
        vertex_count = 3
        edge_count = 3
        indptr = np.asarray([0, 2, 3, 3], dtype=np.int64)
        targets = np.asarray([2, 1, 2], dtype=np.int32)
        distances = np.asarray([10.0, 6.0, 6.0], dtype=np.float32)
        _coordinates = [(0.0, 0.0), (0.0, 0.01), (0.0, 0.02)]

        def coordinates(self, node: int) -> tuple[float, float]:
            return self._coordinates[node]

    graph = TinyGraph()
    # 0 -> 2 is a 10 km residential route (30 min).
    # 0 -> 1 -> 2 is a 12 km primary-road route (18 min), so time A* should select it.
    codes = np.asarray([12, 5, 5], dtype=np.uint8)
    code_names = {0: "road", 5: "primary", 12: "residential"}
    result = time_astar(graph, 0, 2, codes, code_names, conditions={})
    assert result is not None, "Expected the tiny graph to be routable."
    assert result["path"] == [0, 1, 2], result
    assert abs(result["distance_km"] - 12.0) < 1e-5, result
    assert abs(result["estimated_time_minutes"] - 18.0) < 1e-5, result

    # Mark the first edge of the primary route blocked; the direct route should remain.
    blocked_result = time_astar(
        graph, 0, 2, codes, code_names,
        conditions={(0, 1): {"status": "blocked"}},
    )
    assert blocked_result is not None, "Direct route should remain available."
    assert blocked_result["path"] == [0, 2], blocked_result
    assert abs(blocked_result["estimated_time_minutes"] - 30.0) < 1e-5, blocked_result
    print("Time-aware A* self-test passed.")
    print("Verified: travel-time route choice, physical distance reporting, and blocked-edge avoidance.")
    print("No Tamil Nadu graph files or live dispatch records were opened.")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--self-test", action="store_true", help="Run synthetic tests only")
    args = parser.parse_args()
    if args.self_test:
        _self_test()
        return 0
    parser.print_help()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
